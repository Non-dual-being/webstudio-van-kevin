// Small repeatable local contract checks. No app boot, network or live data.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const work = mkdtempSync(join(tmpdir(), 'kw-deploy-check-'));
const config = JSON.parse(readFileSync(join(here, 'release.example.json')));
const render = (file, dir) => execFileSync(process.execPath, [join(here, 'render.mjs'), file, dir], { stdio: 'pipe' });
assert.throws(() => render(join(here, 'release.example.json'), join(work, 'rejected')));
assert(!existsSync(join(work, 'rejected')));
config.reviewed = true;
const file = join(work, 'reviewed.json');
writeFileSync(file, JSON.stringify(config));
assert.throws(() => render(file, join(work, 'incomplete')));
config.siteCertificate = 'kevinwebstudio.nl'; config.demoCertificate = 'onderwijsdemo.kevinwebstudio.nl';
writeFileSync(file, JSON.stringify(config));
render(file, join(work, 'rendered'));
assert.throws(() => render(file, join(work, 'rendered')));
assert.throws(() => render(file, join(here, '../..not-outside')));
assert(!existsSync(join(here, '../..not-outside')));
const read = name => readFileSync(join(work, 'rendered', name), 'utf8');
const router = readFileSync(join(here, '../demos/onderwijsformulier/server/router.php'), 'utf8');
const api = router.match(/\$routes = \[(.*?)\];/s)[1];
const routes = [...api.matchAll(/'([a-z]+)' => '(?:GET|POST)'/g)].map(m => m[1]);
assert.equal(routes.length, 9);
assert(read('kw-sites.conf').includes(`^/demo-api/(${routes.join('|')})$`));
assert(read('kw-demo-fastcgi.conf').includes('SCRIPT_FILENAME /server/router.php;'));
assert(read('kw-demo-fastcgi.conf').includes('REQUEST_URI $request_uri;'));
assert(read('fpm-demo.conf').includes('chroot = /var/www/onderwijsdemo/current'));
assert(!/^env\[DEMO_TODAY\]/m.test(read('fpm-demo.conf')));
assert(read('kw-contact-worker.service').includes('--queue=contact-mail --sleep=3 --tries=1 --timeout=60'));
assert(read('kw-scheduler.timer').includes('Persistent=false'));
console.log('Render guards and route/runtime/service contracts passed. No Nginx/FPM execution implied.');
